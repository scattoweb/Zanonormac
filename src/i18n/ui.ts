export function useT(lang: Lang) {
  return (key: UiKey, vars: Record<string, string | number> = {}) => {
    let s = ui[key][lang] || ui[key].it;
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

